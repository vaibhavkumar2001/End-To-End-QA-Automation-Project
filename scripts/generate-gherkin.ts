import 'dotenv/config';
import OpenAI from 'openai';
import fs from 'node:fs';
import path from 'node:path';

// Model name can be overridden from .env without touching the code
const MODEL = process.env.OPENAI_MODEL || 'gpt-4o-mini';

// Reads steps/*.ts and returns every step text, so the LLM can reuse them
function collectExistingSteps(): string[] {
  const dir = path.join(process.cwd(), 'steps');
  const pattern = /(?:Given|When|Then)\(\s*'([^']+)'/g;
  const steps: string[] = [];

  for (const file of fs.readdirSync(dir)) {
    if (!file.endsWith('.ts')) continue;
    const source = fs.readFileSync(path.join(dir, file), 'utf-8');
    for (const match of source.matchAll(pattern)) {
      steps.push(match[1]);
    }
  }
  return steps;
}

function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 50);
}

async function main() {
  const story = process.argv.slice(2).join(' ').trim();

  if (!story) {
    console.error('Usage: npx tsx scripts/generate-gherkin.ts "<user story>"');
    process.exit(1);
  }
  if (!process.env.OPENAI_API_KEY) {
    console.error('OPENAI_API_KEY is missing. Add it to your .env file.');
    process.exit(1);
  }

  const existingSteps = collectExistingSteps();
  const client = new OpenAI(); // reads OPENAI_API_KEY from the environment

  const system = [
    'You write Gherkin feature files for a SauceDemo (e-commerce) test suite.',
    'Rules:',
    '- Output only the feature file text. No markdown fences and no commentary.',
    '- Reuse the existing step texts provided by the user exactly when they fit.',
    '- Put values in double quotes, for example: When I add "sauce-labs-backpack" to the cart',
    '- Write 2 to 4 scenarios: one happy path and at least one negative or edge case.',
    '- Use business language. No CSS selectors, URLs or code.',
    '- Do not invent features that the story does not mention.',
  ].join('\n');

  const userMessage = [
    `User story: ${story}`,
    '',
    'Existing step definitions (reuse these when possible):',
    ...existingSteps.map((s) => `- ${s}`),
  ].join('\n');

  const response = await client.chat.completions.create({
    model: MODEL,
    messages: [
      { role: 'system', content: system },
      { role: 'user', content: userMessage },
    ],
  });

  const text = (response.choices[0]?.message?.content ?? '')
    // Remove accidental markdown fences if the model adds them
    .replace(/^```(?:gherkin)?\s*/i, '')
    .replace(/```\s*$/, '')
    .trim();

  if (!text) {
    console.error('The model returned an empty response.');
    process.exit(1);
  }

  const outDir = path.join(process.cwd(), 'generated');
  fs.mkdirSync(outDir, { recursive: true });

  const outFile = path.join(outDir, `${slugify(story)}.feature.draft`);
  const header = '# DRAFT generated by an LLM. Review it before moving it to features/ as a .feature file.\n';
  fs.writeFileSync(outFile, `${header}${text}\n`, 'utf-8');

  console.log(`Draft written to ${path.relative(process.cwd(), outFile)}`);
}

main().catch((error) => {
  console.error('Generation failed:', error instanceof Error ? error.message : error);
  process.exit(1);
});